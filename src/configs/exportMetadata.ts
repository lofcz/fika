/**
 * Host-mandated document metadata for PPTX and PDF downloads.
 *
 * Lets a host mark exported files as machine-generated in a machine-readable
 * way (for example to meet EU AI Act art. 50 transparency duties) without
 * touching slide content. Like `exportWatermark`, the resolver runs at the
 * start of every export, so the host can decide per download. Returning
 * null/undefined leaves Fika's default metadata untouched. A resolver that
 * throws, or metadata that cannot be written, fails the export — the engine
 * never silently drops a label the host asked for.
 */

/** Custom XMP namespace written next to the standard PDF XMP fields. */
export interface FikaExportMetadataXmpNamespace {
  /** Namespace URI, e.g. `https://example.com/ns/ai/1.0/`. */
  uri: string
  /** XML prefix, e.g. `acme`. Must not clash with `x`, `rdf`, `xml`, `xmp`, `pdf`, `dc` or `Iptc4xmpExt`. */
  prefix: string
  /** Simple text properties, e.g. `{ aiGenerated: 'True' }`. Names must be XML names. */
  properties: Record<string, string>
}

export interface FikaExportMetadata {
  /**
   * Producing application. PPTX: `docProps/app.xml` `<Application>` and the
   * `Generator` custom property. PDF: Info `Creator` / `Producer`,
   * XMP `xmp:CreatorTool` / `pdf:Producer`.
   */
  generator: string
  /**
   * Whether the content was generated by AI. PPTX: custom property
   * `AIGenerated` (bool) and, when true, the `AI-generated` keyword.
   * PDF: Info key `AIGenerated`.
   */
  aiGenerated: boolean
  /**
   * IPTC digital source type URI, e.g.
   * `http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia`.
   * PPTX: custom property `DigitalSourceType`. PDF: Info key
   * `DigitalSourceType`, XMP `Iptc4xmpExt:DigitalSourceType`.
   */
  digitalSourceType: string
  /**
   * Human-readable disclosure, e.g. `Generated by AI in Acme`. PPTX:
   * `dc:description` when the deck has none. PDF: Info key `AIStatement`,
   * XMP `dc:description`.
   */
  statement?: string
  /** Overrides the document title (PPTX `dc:title`, PDF Info `Title` and XMP `dc:title`). */
  title?: string
  /** Extra XMP namespace for host-specific flags (PDF only). */
  xmpNamespace?: FikaExportMetadataXmpNamespace
}

export interface FikaExportMetadataContext {
  /** Format being written. */
  format: 'pptx' | 'pdf'
  /** Deck title at export time. */
  title: string
}

export type FikaExportMetadataResolver = (context: FikaExportMetadataContext) =>
  | FikaExportMetadata
  | null
  | undefined
  | Promise<FikaExportMetadata | null | undefined>

let exportMetadataResolver: FikaExportMetadataResolver | null = null

export function setFikaExportMetadata(resolver?: FikaExportMetadataResolver | null) {
  exportMetadataResolver = resolver ?? null
}

export function getFikaExportMetadata(): FikaExportMetadataResolver | null {
  return exportMetadataResolver
}

/**
 * Runs the resolver and validates the result. Returns a plain, structured-
 * cloneable object (safe to post to the export worker) or null.
 */
export async function resolveExportMetadata(
  resolver: FikaExportMetadataResolver | null | undefined,
  context: FikaExportMetadataContext,
): Promise<FikaExportMetadata | null> {
  if (!resolver) return null
  const value = await resolver(context)
  if (!value) return null
  const text = (field: string, input: unknown, required: boolean) => {
    if (input === undefined && !required) return undefined
    if (typeof input !== 'string' || (required && !input.trim())) throw new Error(`Invalid export metadata: ${field} must be a non-empty string`)
    return input
  }
  if (typeof value.aiGenerated !== 'boolean') throw new Error('Invalid export metadata: aiGenerated must be a boolean')
  const metadata: FikaExportMetadata = {
    generator: text('generator', value.generator, true)!,
    aiGenerated: value.aiGenerated,
    digitalSourceType: text('digitalSourceType', value.digitalSourceType, true)!,
  }
  const statement = text('statement', value.statement, false)
  if (statement) metadata.statement = statement
  const title = text('title', value.title, false)
  if (title) metadata.title = title
  if (value.xmpNamespace) {
    const { uri, prefix, properties } = value.xmpNamespace
    const name = /^[A-Za-z_][A-Za-z0-9._-]*$/
    if (typeof uri !== 'string' || !uri.trim()) throw new Error('Invalid export metadata: xmpNamespace.uri must be a non-empty string')
    if (typeof prefix !== 'string' || !name.test(prefix) || /^(x|rdf|xml.*|xmp|pdf|dc|Iptc4xmpExt)$/i.test(prefix)) {
      throw new Error(`Invalid export metadata: xmpNamespace.prefix "${prefix}" is not a usable XML prefix`)
    }
    if (!properties || typeof properties !== 'object') throw new Error('Invalid export metadata: xmpNamespace.properties must be an object')
    const entries = Object.entries(properties)
    for (const [key, entry] of entries) {
      if (!name.test(key)) throw new Error(`Invalid export metadata: xmpNamespace property "${key}" is not an XML name`)
      if (typeof entry !== 'string') throw new Error(`Invalid export metadata: xmpNamespace property "${key}" must be a string`)
    }
    metadata.xmpNamespace = { uri, prefix, properties: Object.fromEntries(entries) }
  }
  return metadata
}
