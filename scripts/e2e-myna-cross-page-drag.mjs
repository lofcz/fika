import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1800, height: 1200 } })
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto(`${process.env.FIKA_TEST_URL || 'http://127.0.0.1:5173'}/?mode=myna&locale=en`)
  await page.locator('[data-myna-page-handle]').first().waitFor()
  await page.waitForTimeout(900)
  // A frame with a child verifies that hierarchy and IDs survive the page transfer.
  await page.getByRole('button', { name: 'Layers', exact: true }).click()
  const panel = page.locator('[data-myna-frames-hierarchy]')
  const original = await page.evaluate(() => { const s = window.__FIKA_SLIDES__.getState(); return s.slides[s.slideIndex] })
  const child = original.elements.find(el => el.type === 'shape' && el.height > 150)
  await panel.locator(`[data-frame-element-id="${child.id}"]`).click()
  await panel.getByRole('button', { name: 'Frame selection', exact: true }).click()
  const frame = await page.evaluate(() => { const s = window.__FIKA_SLIDES__.getState(); return s.slides[s.slideIndex].elements.find(el => el.frame) })
  await panel.getByRole('button', { name: 'Frame selection', exact: true }).click()
  await panel.locator(`[data-frame-element-id="${frame.id}"]`).click()
  await page.getByRole('button', { name: 'Fit all pages', exact: true }).click()
  await page.waitForTimeout(400)
  const before = await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides)
  const target = before.find(s => s.id !== original.id)
  const start = await page.locator(`[data-myna-frame-title="${frame.id}"]`).boundingBox()
  const dest = await page.locator(`[data-myna-page-id="${target.id}"]`).boundingBox()
  await page.keyboard.down('Alt')
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
  await page.mouse.down()
  await page.mouse.move(dest.x + dest.width / 2, dest.y + dest.height / 2, { steps: 15 })
  await page.waitForTimeout(80)
  assert.equal(await page.locator('.viewport-clip').evaluate(n => getComputedStyle(n).overflow), 'visible', 'drag preview is not clipped at source page')
  assert.equal(await page.locator(`#editable-element-${frame.id}`).evaluate(n => getComputedStyle(n).clipPath), 'none', 'moving root can escape its old parent clip')
  const live = await page.locator(`#editable-element-${frame.id} > *`).first().boundingBox()
  await page.mouse.up(); await page.keyboard.up('Alt')
  await page.waitForTimeout(450)
  const after = await page.evaluate(() => { const s = window.__FIKA_SLIDES__.getState(); return { slides: s.slides, index: s.slideIndex } })
  assert.equal(after.slides[after.index].id, target.id, 'destination becomes editable')
  const from = after.slides.find(s => s.id === original.id), to = after.slides.find(s => s.id === target.id)
  assert.ok(!from.elements.some(el => el.id === frame.id || el.id === child.id), 'source loses complete subtree')
  assert.equal(to.elements.find(el => el.id === frame.id).parentFrameId, undefined, 'old parent frame link removed')
  assert.equal(to.elements.find(el => el.id === child.id).parentFrameId, frame.id, 'nested parent preserved')
  const dropped = await page.locator(`#editable-element-${frame.id} > *`).first().boundingBox()
  assert.ok(Math.abs(live.x - dropped.x) < 1 && Math.abs(live.y - dropped.y) < 1, 'no position jump on reparent')
  assert.equal(await page.locator('.viewport-clip').evaluate(n => getComputedStyle(n).overflow), 'visible', 'workspace overflow stays visible after drop')
  await page.evaluate(() => window.__FIKA_SNAPSHOT__.getState().unDo())
  await page.waitForTimeout(100)
  const undone = await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides)
  assert.deepEqual(undone.map(s => s.elements), before.map(s => s.elements), 'one undo restores both pages')
  await page.locator(`[data-myna-page-handle="${original.id}"]`).press('Enter')
  await panel.locator(`[data-frame-element-id="${frame.id}"]`).click()
  const copyStart = await page.locator(`[data-myna-frame-title="${frame.id}"]`).boundingBox()
  const copyDest = await page.locator(`[data-myna-page-id="${target.id}"]`).boundingBox()
  await page.keyboard.down('Control')
  await page.keyboard.down('Alt')
  await page.mouse.move(copyStart.x + copyStart.width / 2, copyStart.y + copyStart.height / 2)
  await page.mouse.down()
  await page.mouse.move(copyDest.x + copyDest.width / 2, copyDest.y + copyDest.height / 2, { steps: 12 })
  await page.mouse.up()
  await page.keyboard.up('Alt'); await page.keyboard.up('Control')
  await page.waitForTimeout(400)
  const copied = await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides)
  assert.deepEqual(copied.find(s => s.id === original.id).elements, before.find(s => s.id === original.id).elements, 'copy-drag preserves source artwork')
  const originals = new Set(before.flatMap(s => s.elements.map(el => el.id)))
  const added = copied.find(s => s.id === target.id).elements.filter(el => !originals.has(el.id))
  assert.equal(added.length, 1 + before.find(s => s.id === original.id).elements.filter(el => el.parentFrameId === frame.id).length, 'copy-drag transfers entire duplicated subtree')
  assert.equal(added.find(el => !el.frame).parentFrameId, added.find(el => el.frame).id)
  assert.deepEqual(errors, [])
  console.log('PASS cross-page drag: live overflow, subtree transfer, stable world position, active destination, undo, and copy-drag')
} finally { await browser.close() }
