import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1500, height: 950 } })
page.setDefaultTimeout(15000)
const errors = []
page.on('pageerror', error => errors.push(error.message))
const base = process.env.FIKA_TEST_URL || 'http://127.0.0.1:5178'
try {
  await page.goto(`${base}/?mode=myna&locale=en`, { waitUntil: 'networkidle' })
  const library = page.locator('details').filter({ has: page.locator('summary', { hasText: 'Personal templates' }) })
  await library.waitFor()
  assert.equal(await library.getAttribute('open'), null)
  await library.locator('summary').press('Enter')
  await library.getByRole('textbox', { name: 'Template name', exact: true }).fill('Library test')
  const before = await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides.map(s => s.id))
  await library.getByRole('button', { name: 'Save this design', exact: true }).click()
  await library.getByRole('status').getByText('Design saved as a personal template.').waitFor()
  await library.getByRole('button', { name: 'Favorite', exact: true }).click()
  await library.getByRole('button', { name: 'Favorites', exact: true }).click()
  await library.getByRole('button', { name: 'Add all pages: Library test', exact: true }).click()
  await page.waitForFunction(n => window.__FIKA_SLIDES__.getState().slides.length === n * 2, before.length)
  const after = await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides.map(s => s.id))
  assert.equal(new Set(after).size, after.length)
  await page.waitForTimeout(350)
  await page.locator('[data-canvas-tool=undo]').click()
  await page.waitForFunction(n => window.__FIKA_SLIDES__.getState().slides.length === n, before.length)
  await page.reload({ waitUntil: 'networkidle' })
  assert.notEqual(await library.getAttribute('open'), null)
  await library.getByRole('button', { name: 'Rename', exact: true }).click()
  await library.getByRole('textbox', { name: 'Template name', exact: true }).last().fill('Renamed design')
  await library.getByRole('button', { name: 'Rename', exact: true }).first().click()
  await library.getByRole('textbox', { name: 'Search personal templates' }).fill('Renamed')
  await library.getByRole('button', { name: 'Add all pages: Renamed design', exact: true }).waitFor()
  await page.screenshot({ path: 'output/myna/parity-library.png' })
  await page.evaluate(() => window.__FIKA_MAIN__.getState().setReadOnly(true))
  assert.equal(await library.getByRole('button', { name: 'Add all pages: Renamed design', exact: true }).isDisabled(), true)
  await page.evaluate(() => window.__FIKA_MAIN__.getState().setReadOnly(false))
  await library.getByRole('button', { name: 'Delete', exact: true }).click()
  await library.getByRole('button', { name: 'Delete', exact: true }).last().click()
  assert.equal(await library.getByRole('button', { name: 'Add all pages: Renamed design', exact: true }).count(), 0)
  assert.deepEqual(errors, [])
  console.log('Personal templates: compact disclosure, save, favorite, insert, undo, persistence, rename, search, read-only and confirmed deletion passed.')
} finally { await browser.close() }
