import assert from 'node:assert/strict'
import { readFile, mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const labels = () => page.evaluate(() => window.__FIKA_SLIDES__.getState().slides.flatMap(slide => slide.workspaceLabels || []))
try {
  await page.addInitScript(() => localStorage.setItem('fika:myna:view:v1', JSON.stringify({ snapPagesToGrid: true, gridSize: 20 })))
  await page.goto(`${process.env.FIKA_TEST_URL || 'http://127.0.0.1:5178'}/?mode=myna&locale=en`, { waitUntil: 'networkidle' })
  await page.locator('[data-myna-workspace]').waitFor()
  await page.waitForFunction(() => window.__FIKA_SNAPSHOT__?.getState().snapshotLength > 0)
  // Isolate the label workflow from the evolving showcase content.
  await page.evaluate(async () => {
    const store = window.__FIKA_SLIDES__.getState()
    store.setSlides([{ ...store.slides[0], canvasPosition: { x: 0, y: 0 }, workspaceLabels: [] }])
    store.updateSlideIndex(0)
    await window.__FIKA_SNAPSHOT__.getState().initSnapshotDatabase()
  })
  await page.getByRole('button', { name: 'Pages', exact: true }).click()
  const panel = page.locator('[data-myna-workspace-labels-panel]')
  await panel.locator('form input').fill('Concept exploration')
  await panel.getByRole('button', { name: 'Add label', exact: true }).click()
  assert.equal((await labels())[0].text, 'Concept exploration')
  await page.waitForTimeout(400)
  await page.getByRole('button', { name: 'Fit all pages', exact: true }).click()
  await page.waitForTimeout(300)
  const label = page.locator('[data-myna-workspace-label]').first()
  const before = (await labels())[0]
  const box = await label.locator('button').boundingBox()
  assert.ok(box && box.y > 0, 'Fit all includes workspace annotations')
  await page.mouse.move(box.x + 12, box.y + 12); await page.mouse.down()
  await page.mouse.move(box.x + 79, box.y + 43, { steps: 10 }); await page.mouse.up()
  await page.waitForTimeout(400)
  const moved = (await labels())[0]
  assert.ok(moved.x > before.x && moved.y > before.y, 'Dragging stores world position')
  assert.equal(moved.x % 20, 0, 'Label snaps to grid x'); assert.equal(Math.abs(moved.y % 20), 0, 'Label snaps to grid y')
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(250)
  assert.equal((await labels())[0].x, before.x)
  // Alt bypasses quantization; Shift keeps the starting coordinate on the locked axis.
  const freeStart = await label.locator('button').boundingBox()
  await page.keyboard.down('Alt')
  await page.mouse.move(freeStart.x + 12, freeStart.y + 12); await page.mouse.down()
  await page.mouse.move(freeStart.x + 29, freeStart.y + 21, { steps: 6 }); await page.mouse.up(); await page.keyboard.up('Alt')
  assert.ok((await labels())[0].x % 20 !== 0 || (await labels())[0].y % 20 !== 0, 'Alt bypasses grid')
  const unlocked = (await labels())[0], constrained = await label.locator('button').boundingBox()
  await page.keyboard.down('Shift')
  await page.mouse.move(constrained.x + 12, constrained.y + 12); await page.mouse.down()
  await page.mouse.move(constrained.x + 79, constrained.y + 18, { steps: 6 }); await page.mouse.up(); await page.keyboard.up('Shift')
  assert.equal((await labels())[0].y, unlocked.y, 'Shift preserves original y even off grid')
  assert.equal((await labels())[0].x % 20, 0)
  await label.locator('button').dblclick()
  await label.locator('textarea').fill('Approved direction')
  await label.locator('textarea').press('Enter')
  assert.equal((await labels())[0].text, 'Approved direction')
  await label.locator('button').dblclick()
  await label.locator('textarea').fill('Cancelled edit')
  await label.locator('textarea').press('Escape')
  assert.equal((await labels())[0].text, 'Approved direction')
  await page.getByRole('button', { name: 'Duplicate page', exact: true }).first().click()
  await page.getByRole('button', { name: 'Fit all pages', exact: true }).click()
  await page.waitForTimeout(300)
  await mkdir('output/myna', { recursive: true })
  await page.screenshot({ path: 'output/myna/workspace-labels.png' })
  assert.equal((await labels()).length, 1, 'Duplicating a page does not duplicate workspace annotations')
  await page.evaluate(() => { const store = window.__FIKA_SLIDES__.getState(); store.deleteSlide(store.slides.find(slide => slide.workspaceLabels?.length).id) })
  assert.equal((await labels())[0].text, 'Approved direction', 'Labels survive storage page deletion')
  await page.getByRole('button', { name: 'Download', exact: true }).first().click()
  const modal = page.locator('.myna-download')
  await modal.locator('select').first().selectOption('svg')
  const pending = page.waitForEvent('download')
  await modal.getByRole('button', { name: 'Download', exact: true }).click()
  const result = await pending
  const svg = await readFile(await result.path(), 'utf8')
  assert.ok(!svg.includes('Approved direction'), 'Workspace labels do not leak into page SVG artwork')
  await page.evaluate(() => window.__FIKA_MAIN__.getState().setReadOnly(true))
  assert.ok(await panel.getByRole('button', { name: 'Add label', exact: true }).isDisabled())
  await label.locator('button').press('Delete')
  assert.equal((await labels()).length, 1, 'Read only disallows deletion')
  assert.deepEqual(errors, [])
  console.log('Workspace label creation, camera bounds, drag, undo, edit/cancel and read-only passed')
} finally { await browser.close() }
