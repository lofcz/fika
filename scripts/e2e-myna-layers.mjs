import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const state = () => page.evaluate(() => window.__FIKA_SLIDES__.getState().slides[0])
const ids = async () => (await state()).elements.map(element => element.id)
const history = command => page.evaluate(command => window.__FIKA_SNAPSHOT__.getState()[command](), command)
async function mutation(run) {
  const before = await page.evaluate(() => window.__FIKA_SNAPSHOT__.getState().snapshotCursor)
  await run()
  await page.waitForFunction(previous => window.__FIKA_SNAPSHOT__.getState().snapshotCursor > previous, before)
}
const row = name => page.locator('.layer-card').filter({ has: page.getByRole('button', { name, exact: true }) })
const action = (name, label) => row(name).getByRole('button', { name: label, exact: true })
try {
  await page.goto(`${process.env.FIKA_TEST_URL || 'http://127.0.0.1:5178'}/?mode=myna&locale=en`, { waitUntil: 'networkidle' })
  await page.locator('[data-myna-workspace]').waitFor()
  await page.waitForFunction(() => window.__FIKA_SNAPSHOT__?.getState().snapshotLength > 0)
  await page.evaluate(async () => {
    const shape = (id, name, left, groupId) => ({ id, name, type: 'shape', left, top: 150, width: 100, height: 100, rotate: 0, viewBox: [100, 100], path: 'M0 0H100V100H0Z', fill: '#42584a', fixedRatio: false, ...(groupId ? { groupId } : {}) })
    const s = window.__FIKA_SLIDES__.getState()
    s.updateSlideIndex(0)
    s.setSlides([{ id: 'layers-fixture', background: { type: 'solid', color: '#ffffff' }, elements: [shape('back', 'Back shape', 100), shape('group-a', '', 250, 'pair'), shape('group-b', 'Grouped shapes', 400, 'pair'), shape('front', 'Front shape', 550)], animations: [{ id: 'group-animation', elId: 'group-a', effect: 'fadeIn', type: 'in', duration: 500, trigger: 'click' }] }])
    await window.__FIKA_SNAPSHOT__.getState().addSnapshot()
  })
  await page.getByRole('button', { name: 'Layers', exact: true }).click()
  assert.equal(await page.locator('.layer-card').count(), 3)
  await action('Back shape', 'Rename layer').click()
  const rename = page.getByRole('textbox', { name: 'Layer name', exact: true })
  await rename.fill('Nordic background')
  await mutation(() => rename.press('Enter'))
  assert.equal((await state()).elements[0].name, 'Nordic background')
  const search = page.getByRole('textbox', { name: 'Search layers' })
  await search.fill('nordic')
  assert.equal(await page.locator('.layer-card').count(), 1)
  await search.fill('not present')
  assert.equal(await page.locator('.layer-card').count(), 0)
  await search.fill('')
  await action('Nordic background', 'Rename layer').click()
  await rename.fill('Cancelled rename')
  await rename.press('Escape')
  assert.equal((await state()).elements[0].name, 'Nordic background')
  await mutation(() => action('Grouped shapes', 'Duplicate layer').click())
  const duplicated = (await state()).elements
  assert.equal(duplicated.length, 6)
  assert.equal(duplicated[4].groupId, duplicated[5].groupId)
  assert.notEqual(duplicated[4].groupId, 'pair')
  assert.equal(new Set(duplicated.map(element => element.id)).size, 6)
  await history('unDo')
  assert.equal((await state()).elements.length, 4)
  await history('reDo')
  assert.equal((await state()).elements.length, 6)
  await history('unDo')
  await mutation(() => action('Grouped shapes', 'Lock layer').click())
  assert.ok((await state()).elements.filter(element => element.groupId === 'pair').every(element => element.lock))
  for (const label of ['Duplicate layer', 'Delete layer']) assert.equal(await action('Grouped shapes', label).isDisabled(), true)
  assert.equal(await row('Grouped shapes').getAttribute('draggable'), 'false')
  await mutation(() => action('Grouped shapes', 'Unlock layer').click())
  await action('Grouped shapes', 'Hide layer').click()
  assert.deepEqual(await page.evaluate(() => window.__FIKA_MAIN__.getState().hiddenElementIdList), ['group-a', 'group-b'])
  await action('Grouped shapes', 'Show layer').click()
  await mutation(() => row('Front shape').dragTo(row('Nordic background')))
  assert.deepEqual(await ids(), ['front', 'back', 'group-a', 'group-b'])
  await history('unDo')
  assert.deepEqual(await ids(), ['back', 'group-a', 'group-b', 'front'])
  await mutation(() => row('Grouped shapes').dragTo(row('Front shape')))
  assert.deepEqual(await ids(), ['back', 'front', 'group-a', 'group-b'])
  await mutation(() => action('Grouped shapes', 'Grouped shapes').press('Alt+ArrowDown'))
  assert.deepEqual(await ids(), ['back', 'group-a', 'group-b', 'front'])
  await mutation(() => action('Grouped shapes', 'Delete layer').click())
  assert.deepEqual(await ids(), ['back', 'front'])
  assert.deepEqual((await state()).animations, [])
  await history('unDo')
  assert.equal((await state()).elements.length, 4)
  assert.equal((await state()).animations[0].elId, 'group-a')
  await page.evaluate(() => window.__FIKA_MAIN__.getState().setReadOnly(true))
  for (const label of ['Rename layer', 'Duplicate layer', 'Delete layer', 'Lock layer', 'Hide layer', 'Bring forward', 'Send backward']) {
    const buttons = page.locator('.layer-card').getByRole('button', { name: label, exact: true })
    assert.ok(await buttons.count() > 0, label)
    for (const button of await buttons.all()) assert.equal(await button.isDisabled(), true, label)
  }
  assert.equal(await row('Grouped shapes').getAttribute('draggable'), 'false')
  assert.deepEqual(errors, [])
  console.log('Myna layers: groups, fresh IDs, rename/search, lock/visibility, drag/keyboard ordering, animation cleanup, undo and read-only passed.')
} finally { await browser.close() }
