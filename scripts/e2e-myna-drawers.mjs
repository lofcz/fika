import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1500, height: 950 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto(`${process.env.FIKA_TEST_URL || 'http://127.0.0.1:5178'}/?mode=myna&locale=en`, { waitUntil: 'networkidle' })
  const drawer = page.locator('#myna-library')
  await drawer.waitFor()
  const separator = drawer.getByRole('separator')
  await separator.focus()
  await page.keyboard.press('ArrowRight')
  assert.equal(await separator.getAttribute('aria-valuenow'), '316')
  await drawer.getByRole('button', { name: 'Unpin panel', exact: true }).click()
  assert.equal(await drawer.evaluate(el => getComputedStyle(el).position), 'absolute')
  await drawer.getByRole('button', { name: 'Pin panel', exact: true }).click()
  await page.getByRole('button', { name: 'Pages', exact: true }).click()
  await drawer.getByRole('button', { name: 'Add page', exact: true }).click()
  await page.waitForFunction(() => window.__FIKA_SLIDES__.getState().slides.length === 2)
  await drawer.getByRole('button', { name: 'Duplicate page', exact: true }).last().click()
  await page.waitForFunction(() => window.__FIKA_SLIDES__.getState().slides.length === 3)
  await drawer.getByRole('button', { name: 'Move page up', exact: true }).last().click()
  assert.equal(await page.evaluate(() => window.__FIKA_SLIDES__.getState().slideIndex), 1)
  await drawer.getByRole('button', { name: 'Delete page', exact: true }).last().click()
  await page.waitForFunction(() => window.__FIKA_SLIDES__.getState().slides.length === 2)
  await drawer.getByRole('textbox', { name: 'Search pages' }).fill('Ideas into')
  assert.equal(await drawer.getByRole('button', { name: 'Duplicate page', exact: true }).count(), 1)
  await page.getByRole('button', { name: 'Assets', exact: true }).click()
  await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 20; canvas.height = 20
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#264539'; ctx.fillRect(0, 0, 20, 20)
    window.__FIKA_SLIDES__.getState().addElement({ id: 'myna-test-image', type: 'image', src: canvas.toDataURL(), name: 'Forest', left: 100, top: 100, width: 100, height: 100, rotate: 0, fixedRatio: true })
  })
  await drawer.getByRole('button', { name: 'Insert Forest', exact: true }).click()
  await page.waitForFunction(() => window.__FIKA_SLIDES__.getState().slides.flatMap(s => s.elements).filter(e => e.type === 'image').length === 2)
  assert.ok((await drawer.innerText()).includes('Used 2 times'))
  await page.evaluate(() => window.__FIKA_MAIN__.getState().setReadOnly(true))
  assert.equal(await drawer.getByRole('button', { name: 'Insert Forest', exact: true }).isDisabled(), true)
  await page.evaluate(() => window.__FIKA_MAIN__.getState().setReadOnly(false))
  await page.getByRole('button', { name: 'Close properties', exact: true }).click()
  await drawer.getByRole('textbox', { name: 'Search assets' }).focus()
  await page.keyboard.press('Escape')
  assert.equal(await drawer.count(), 0)
  await page.setViewportSize({ width: 600, height: 850 })
  await page.getByRole('button', { name: 'Design', exact: true }).click()
  assert.equal(await drawer.evaluate(el => getComputedStyle(el).position), 'absolute')
  await page.screenshot({ path: 'output/myna/drawers-narrow.png' })
  assert.deepEqual(errors, [])
  console.log('Myna drawers: keyboard resize, pinning, page overview, media reuse, read-only, Escape and narrow overlay passed.')
} finally { await browser.close() }
