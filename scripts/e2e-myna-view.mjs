import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const base = process.env.FIKA_TEST_URL || 'http://127.0.0.1:5178'
const view = page.getByRole('dialog', { name: 'View', exact: true })
const current = () => page.evaluate(() => { const state = window.__FIKA_SLIDES__.getState(); return state.slides[state.slideIndex] })
async function openView() {
  await page.getByRole('button', { name: 'View', exact: true }).click()
  await view.waitFor()
}
try {
  await page.goto(`${base}/?mode=myna&locale=en`, { waitUntil: 'networkidle' })
  await page.waitForFunction(() => window.__FIKA_SNAPSHOT__?.getState().snapshotLength > 0)
  await openView()
  assert.equal(await view.getByLabel('Show rulers', { exact: true }).isChecked(), true)
  assert.equal(await view.getByLabel('Show guides', { exact: true }).isChecked(), true)
  assert.equal(await view.getByLabel('Snap to guides', { exact: true }).isChecked(), true)
  assert.equal(await view.getByLabel('Show layout grid').isChecked(), false)
  assert.equal(await view.getByLabel('Grid spacing').isDisabled(), true)
  await view.getByLabel('Show layout grid').check()
  await view.getByLabel('Grid spacing').fill('48')
  await view.getByLabel('Grid spacing').press('Enter')
  await view.getByLabel('Show rulers', { exact: true }).uncheck()
  await view.getByLabel('Snap to guides', { exact: true }).uncheck()
  await view.getByLabel('Lock guides', { exact: true }).check()
  await view.getByLabel('Grid spacing').fill('900')
  await view.getByLabel('Grid spacing').press('Enter')
  assert.equal(await view.getByLabel('Grid spacing').inputValue(), '48')
  await view.getByLabel('Show guides', { exact: true }).press('Escape')
  await view.waitFor({ state: 'hidden' })
  assert.equal(await page.getByRole('button', { name: 'View', exact: true }).evaluate(element => element === document.activeElement), true)
  await page.reload({ waitUntil: 'networkidle' })
  await openView()
  assert.equal(await view.getByLabel('Show rulers', { exact: true }).isChecked(), false)
  assert.equal(await view.getByLabel('Snap to guides', { exact: true }).isChecked(), false)
  assert.equal(await view.getByLabel('Show layout grid').isChecked(), true)
  assert.equal(await view.getByLabel('Grid spacing').inputValue(), '48')
  assert.equal(await view.getByLabel('Lock guides', { exact: true }).isChecked(), true)
  await page.evaluate(async () => {
    window.__FIKA_SLIDES__.getState().updateSlide({ guides: [{ id: 'test-x', axis: 'x', position: 120 }, { id: 'test-y', axis: 'y', position: 160 }] })
    await window.__FIKA_SNAPSHOT__.getState().addSnapshot()
  })
  const clear = view.getByRole('button', { name: 'Clear page guides', exact: true })
  assert.equal(await clear.isDisabled(), true)
  await view.getByLabel('Lock guides', { exact: true }).uncheck()
  const cursor = await page.evaluate(() => window.__FIKA_SNAPSHOT__.getState().snapshotCursor)
  await clear.click()
  assert.deepEqual((await current()).guides, [])
  await page.waitForFunction(before => window.__FIKA_SNAPSHOT__.getState().snapshotCursor > before, cursor)
  await page.evaluate(() => window.__FIKA_SNAPSHOT__.getState().unDo())
  assert.equal((await current()).guides.length, 2)
  await page.evaluate(() => window.__FIKA_MAIN__.getState().setReadOnly(true))
  assert.equal(await clear.isDisabled(), true)
  await view.getByLabel('Show rulers', { exact: true }).check()
  assert.equal(await view.getByLabel('Show rulers', { exact: true }).isChecked(), true)
  assert.equal((await current()).guides.length, 2)
  assert.deepEqual(errors, [])
  console.log('Myna View: defaults, all preference controls, grid spacing validation, reload persistence, Escape focus, clear guides undo/lock/read-only passed.')
} finally { await browser.close() }
