import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1600, height: 1100 }, permissions: ['clipboard-read', 'clipboard-write'] })
const errors = []; page.on('pageerror', error => errors.push(error.message))
const elements = () => page.evaluate(() => { const s = window.__FIKA_SLIDES__.getState(); return s.slides[s.slideIndex].elements })
const select = async id => { await page.locator(`[data-frame-element-id="${id}"]`).click() }
try {
  await page.goto(`${process.env.FIKA_TEST_URL || 'http://127.0.0.1:5173'}/?mode=myna&locale=en`, { waitUntil: 'networkidle' })
  await page.getByRole('button', { name: 'Layers', exact: true }).click()
  const panel = page.locator('[data-myna-frames-hierarchy]')
  await panel.waitFor()
  const original = await elements(); const child = original.find(el => el.type === 'shape')
  assert.ok(child, 'Starter artwork contains a shape')
  await select(child.id)
  await panel.getByRole('button', { name: 'Frame selection', exact: true }).click()
  let state = await elements(); const inner = state.find(el => el.frame)
  assert.equal(state.find(el => el.id === child.id).parentFrameId, inner.id)
  await panel.getByLabel('Frame name', { exact: true }).fill('Inner frame')
  await panel.getByLabel('Frame name', { exact: true }).press('Enter')
  await panel.getByRole('button', { name: 'Frame selection', exact: true }).click()
  state = await elements(); const outer = state.find(el => el.frame && el.id !== inner.id)
  assert.equal(state.find(el => el.id === inner.id).parentFrameId, outer.id)
  await panel.getByLabel('Frame name', { exact: true }).fill('Outer frame')
  await panel.getByLabel('Frame name', { exact: true }).press('Enter')
  assert.equal(await panel.locator(`[data-frame-element-id="${child.id}"]`).getAttribute('aria-level'), '3')
  // The parent selector excludes self and descendants to prevent cycles.
  const options = await panel.getByLabel('Parent frame', { exact: true }).locator('option').evaluateAll(nodes => nodes.map(n => n.value))
  assert.ok(!options.includes(inner.id) && !options.includes(outer.id))
  await panel.getByLabel('Clip content', { exact: true }).uncheck()
  assert.equal((await elements()).find(el => el.id === outer.id).frame.clipContent, false)
  await panel.getByLabel('Clip content', { exact: true }).check()
  assert.match(await page.locator(`#editable-element-${child.id}`).evaluate(node => node.style.clipPath), /^polygon\(/, 'Nested content has a canvas clipping polygon')
  // Real canvas drag: frame selection stays active while dragging its border.
  await page.waitForTimeout(350)
  const before = await elements()
  const box = await page.locator(`[data-myna-frame-title="${outer.id}"]`).boundingBox()
  assert.ok(box, 'Frame has an editable canvas node')
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  const artwork = page.locator(`#editable-element-${outer.id} > *`).first()
  const artworkBefore = await artwork.boundingBox()
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 55, box.y + box.height / 2 + 35, { steps: 12 })
  await page.waitForTimeout(80)
  const liveTitle = await page.locator(`[data-myna-frame-title="${outer.id}"]`).boundingBox()
  const liveArtwork = await artwork.boundingBox()
  assert.ok(Math.abs(liveTitle.x - box.x) > 5, 'Frame title moves before pointer release')
  assert.ok(Math.abs((liveTitle.x - box.x) - (liveArtwork.x - artworkBefore.x)) < 1, 'Frame title tracks live horizontal artwork movement')
  assert.ok(Math.abs((liveTitle.y - box.y) - (liveArtwork.y - artworkBefore.y)) < 1, 'Frame title tracks live vertical artwork movement')
  await page.mouse.up()
  await page.waitForTimeout(80)
  const settledTitle = await page.locator(`[data-myna-frame-title="${outer.id}"]`).boundingBox()
  assert.ok(Math.abs(settledTitle.x - liveTitle.x) < 1 && Math.abs(settledTitle.y - liveTitle.y) < 1, 'Frame title does not jump on drop')
  await page.waitForTimeout(400)
  state = await elements()
  const moved = state.find(el => el.id === outer.id), prior = before.find(el => el.id === outer.id)
  const dx = moved.left - prior.left, dy = moved.top - prior.top
  assert.ok(Math.abs(dx) + Math.abs(dy) > 1, 'Dragging the parent moves it')
  for (const id of [inner.id, child.id]) {
    const a = before.find(el => el.id === id), b = state.find(el => el.id === id)
    assert.ok(Math.abs(b.left - a.left - dx) < .1 && Math.abs(b.top - a.top - dy) < .1, 'Descendants follow parent drag')
  }
  await page.evaluate(() => window.__FIKA_SNAPSHOT__.getState().unDo())
  assert.equal((await elements()).find(el => el.id === child.id).left, before.find(el => el.id === child.id).left)
  await select(outer.id)
  await mkdir('output/myna', { recursive: true })
  await page.evaluate(() => document.querySelectorAll('[data-react-scan], #react-scan-root').forEach(node => node.remove()))
  await page.screenshot({ path: 'output/myna/nested-frame-hierarchy.png' })
  // Keyboard duplication copies the complete nested subtree with remapped IDs.
  await page.evaluate(() => { document.activeElement?.blur(); window.__FIKA_MAIN__.getState().setEditorareaFocus(true) })
  await page.keyboard.press('Control+d')
  await page.waitForFunction(count => { const s = window.__FIKA_SLIDES__.getState(); return s.slides[s.slideIndex].elements.length === count + 3 }, before.length)
  state = await elements()
  const copies = state.filter(el => !before.some(old => old.id === el.id))
  const copiedOuter = copies.find(el => el.frame && !el.parentFrameId)
  const copiedInner = copies.find(el => el.parentFrameId === copiedOuter.id)
  assert.equal(copies.find(el => !el.frame).parentFrameId, copiedInner.id)
  await select(copiedOuter.id)
  await page.evaluate(() => { document.activeElement?.blur(); window.__FIKA_MAIN__.getState().setEditorareaFocus(true) })
  await page.keyboard.press('Delete')
  await page.waitForTimeout(200)
  assert.equal((await elements()).length, before.length, 'Deleting a frame deletes its subtree')
  await select(inner.id)
  await panel.getByLabel('Parent frame', { exact: true }).selectOption('')
  assert.equal((await elements()).find(el => el.id === inner.id).parentFrameId, undefined)
  await panel.getByLabel('Parent frame', { exact: true }).selectOption(outer.id)
  assert.equal((await elements()).find(el => el.id === inner.id).parentFrameId, outer.id)
  await select(outer.id)
  const saved = JSON.parse(JSON.stringify(await elements()))
  assert.equal(saved.find(el => el.id === inner.id).parentFrameId, outer.id)
  assert.equal(saved.find(el => el.id === child.id).parentFrameId, inner.id)
  assert.equal(saved.find(el => el.id === outer.id).frame.clipContent, true)
  await page.evaluate(() => window.__FIKA_MAIN__.getState().setReadOnly(true))
  assert.equal(await panel.getByRole('button', { name: 'Add frame', exact: true }).isDisabled(), true)
  assert.equal(await panel.getByRole('button', { name: 'Frame selection', exact: true }).isDisabled(), true)
  assert.deepEqual(errors, [])
  console.log('PASS nested-frame UI: frame selection, nesting, names, cycle exclusion, clipping toggle, actual canvas parent drag, descendant movement, undo, duplicate/delete subtree, reparent, JSON metadata, read-only')
} finally { await browser.close() }
