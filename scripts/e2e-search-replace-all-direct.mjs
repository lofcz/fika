import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${process.env.FIKA_TEST_URL || 'http://127.0.0.1:5173/'}?locale=en`, { waitUntil: 'domcontentloaded' })
  await page.waitForFunction(() => window.__FIKA_SNAPSHOT__?.getState().snapshotCursor >= 0)
  await page.evaluate(() => {
    const store = window.__FIKA_SLIDES__.getState()
    store.setSlides([{ id: 'literal-search', elements: [{ id: 'text', type: 'text', left: 100, top: 100, width: 700, height: 100, rotate: 0, defaultFontName: 'Arial', defaultColor: '#000000', content: '<p style="">Price [USD]. [EUR] cost (a+b)?</p>' }] }])
    const first = window.__FIKA_SLIDES__.getState().slides[0]
    store.setSlides([first, { ...structuredClone(first), id: 'second-slide', elements: first.elements.map(el => ({ ...el, id: 'second-text' })) }])
    store.updateSlideIndex(0)
    window.__FIKA_MAIN__.getState().setSearchPanelState(true)
  })
  await page.waitForTimeout(400)
  await page.evaluate(() => window.__FIKA_SNAPSHOT__.getState().initSnapshotDatabase())
  const before = await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides)
  const input = page.getByPlaceholder('Enter text to find')
  await input.fill('Price')
  await page.locator('[class*="search-tabs"]').getByText('Replace', { exact: true }).click()
  await page.getByPlaceholder('Enter replacement text').fill('Cost')
  await page.getByRole('button', { name: 'Replace all', exact: true }).click()
  await page.waitForTimeout(500)
  const after = await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides)
  assert.ok(after.every(slide => slide.elements[0].content.includes('Cost')), 'Replacement is applied across slides')
  assert.equal(await page.evaluate(() => window.__FIKA_SNAPSHOT__.getState().snapshotCursor), 1, 'Replace all creates one undo entry')
  await page.locator('[class*="search-header"] button').click()
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(200)
  assert.deepEqual(await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides), before, 'Undo restores the exact original document')
  await page.keyboard.press('Control+Shift+z')
  await page.waitForTimeout(200)
  assert.deepEqual(await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides), after, 'Redo restores the replacement')
  await page.evaluate(() => window.__FIKA_MAIN__.getState().setSearchPanelState(true))
  await input.fill('No such phrase')
  await page.locator('[class*="search-tabs"]').getByText('Replace', { exact: true }).click()
  await page.getByPlaceholder('Enter replacement text').fill('Unused')
  await page.getByRole('button', { name: 'Replace all', exact: true }).click()
  await page.waitForTimeout(400)
  assert.deepEqual(await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides), after, 'A query with no matches leaves the document unchanged')
  assert.equal(await page.evaluate(() => window.__FIKA_SNAPSHOT__.getState().snapshotCursor), 1, 'A query with no matches creates no undo entry')
  assert.deepEqual(errors, [])
  console.log('PASS Replace all works without a preceding Find action')
} finally { await browser.close() }
