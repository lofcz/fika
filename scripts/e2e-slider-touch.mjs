import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser=await chromium.launch({headless:true})
try {
  const page=await browser.newPage({viewport:{width:1500,height:1000},hasTouch:true})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto(`${process.env.FIKA_TEST_URL||'http://127.0.0.1:5173/'}?locale=en`,{waitUntil:'domcontentloaded'})
  await page.waitForFunction(()=>window.__FIKA_SNAPSHOT__?.getState().snapshotCursor>=0)
  await page.evaluate(()=>{
    const s=window.__FIKA_SLIDES__.getState()
    s.setSlides([{id:'touch-slider',elements:[{id:'shape',type:'shape',left:100,top:100,width:200,height:100,rotate:0,viewBox:[200,100],path:'M0 0H200V100H0Z',fill:'#123456',fixedRatio:false,opacity:1}]}]);s.updateSlideIndex(0)
    window.__FIKA_MAIN__.getState().setActiveElementIdList(['shape'])
  })
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
  await page.evaluate(()=>window.__FIKA_MAIN__.getState().setToolbarState('elStyle'))
  const slider=page.locator('.field').filter({has:page.getByText('Opacity:',{exact:true})}).locator('div').first()
  await slider.scrollIntoViewIfNeeded()
  const r=await slider.boundingBox()
  assert.ok(r)
  const cdp=await page.context().newCDPSession(page)
  const touch=(x)=>({x,y:r.y+r.height/2,id:1,radiusX:2,radiusY:2,force:1})
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[touch(r.x+r.width*.95)]})
  for(let step=1;step<=10;step++) await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[touch(r.x+r.width*(.95-.75*step/10))]})
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  await page.waitForTimeout(200)
  const opacity=await page.evaluate(()=>window.__FIKA_SLIDES__.getState().slides[0].elements[0].opacity)
  console.log({opacity})
  assert.ok(Math.abs(opacity-.2)<.001,'Touch dragging commits the opacity at the release position')
  await page.mouse.move(r.x+r.width*.2,r.y+r.height/2)
  await page.mouse.down()
  await page.mouse.move(r.x+r.width*.8,r.y+r.height/2,{steps:5})
  await page.mouse.up()
  await page.waitForFunction(()=>Math.abs(window.__FIKA_SLIDES__.getState().slides[0].elements[0].opacity-.8)<.001)
  console.log('PASS touch dragging and subsequent mouse dragging')
  assert.deepEqual(errors,[])
} finally {await browser.close()}
