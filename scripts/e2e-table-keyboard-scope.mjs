import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
try {
 const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } })
 const errors = []; page.on('pageerror', e => errors.push(e.message))
 await page.goto(process.env.FIKA_TEST_URL || 'http://127.0.0.1:5173/', { waitUntil: 'domcontentloaded' })
 await page.waitForFunction(() => window.__FIKA_SNAPSHOT__?.getState().snapshotCursor >= 0)
 await page.evaluate(() => {
  const data = [0,1].map(r => [0,1].map(c => ({id:`scope-${r}-${c}`, rowspan:1,colspan:1,text:`Cell ${r} ${c}`})))
  const s = window.__FIKA_SLIDES__.getState()
  s.setSlides([{ id:'scope-slide', elements:[{id:'scope-table',type:'table',left:100,top:100,width:400,height:160,rotate:0,colWidths:[.5,.5],cellMinHeight:80,outline:{width:1,color:'#000',style:'solid'},data}]}]);s.updateSlideIndex(0)
 })
 const root = page.locator('#editable-element-scope-table')
 const cell = root.locator('[data-cell-index="0_0"]'); await cell.waitFor()
 const b = await cell.boundingBox(); await page.mouse.dblclick(b.x+b.width/2,b.y+b.height/2)
 await root.locator('.custom-textarea').focus()
 const title = page.locator('input.title-field')
 const original = await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides[0].elements[0].data)
 for (const key of ['Control+ArrowDown', 'Control+ArrowUp', 'Control+ArrowRight', 'Control+ArrowLeft', 'ArrowLeft', 'ArrowRight']) {
  await title.click()
  await page.keyboard.press(key)
  assert.equal(await title.evaluate(el => document.activeElement === el), true, `${key} keeps title focus`)
  const data = await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides[0].elements[0].data)
  assert.deepEqual(data, original, `${key} in the title must not edit table cells`)
 }
 await title.fill('Title edited while a table cell is selected')
 await page.keyboard.press('Tab')
 assert.equal(await root.locator('.custom-textarea').evaluate(el => document.activeElement === el), false, 'Tab from title follows the page focus order')
 assert.deepEqual(await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides[0].elements[0].data), original)
 await root.locator('.custom-textarea').focus()
 await page.keyboard.press('Control+ArrowDown')
 await page.waitForFunction(() => window.__FIKA_SLIDES__.getState().slides[0].elements[0].data.length === 3)
 assert.equal(await root.locator('.custom-textarea').evaluate(el => document.activeElement === el), true, 'Table shortcuts still work when its editor has focus')
 const first = await root.locator('[data-cell-index="0_0"]').boundingBox()
 const last = await root.locator('[data-cell-index="2_1"]').boundingBox()
 await page.mouse.move(first.x + 10, first.y + 10)
 await page.mouse.down()
 await page.mouse.move(last.x + last.width - 10, last.y + last.height - 10, { steps: 8 })
 await page.mouse.up()
 assert.equal(await root.locator('td.selected').count(), 6, 'Dragging selects the full grid')
 await page.keyboard.press('Delete')
 await page.waitForFunction(() => window.__FIKA_SLIDES__.getState().slides[0].elements[0].data.flat().every(cell => cell.text === ''))
 console.log('PASS table shortcuts respect title focus, preserve table content, allow native Tab, work when returning to the cell editor, and clear dragged cell selections')
 assert.deepEqual(errors,[])
} finally {await browser.close()}
