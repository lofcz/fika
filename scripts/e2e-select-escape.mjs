import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${process.env.FIKA_TEST_URL || 'http://127.0.0.1:5173/'}?locale=en`, { waitUntil: 'domcontentloaded' })
  await page.waitForFunction(() => window.__FIKA_SNAPSHOT__?.getState().snapshotCursor >= 0)
  await page.evaluate(() => {
    const store = window.__FIKA_SLIDES__.getState()
    store.setSlides([{ id: 'escape', elements: [{ id: 'text', type: 'text', left: 100, top: 100, width: 500, height: 100, rotate: 0, defaultFontName: 'Arial', defaultColor: '#000000', content: '<p>Hello</p>' }] }])
    store.updateSlideIndex(0)
    window.__FIKA_MAIN__.getState().setActiveElementIdList(['text'])
  })
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  await page.evaluate(() => window.__FIKA_MAIN__.getState().setToolbarState('elStyle'))
  const select = page.locator('[class*="select-wrap"]').filter({ hasText: 'Arial' }).first()
  await select.click()
  const search = page.locator('[data-tippy-root] input:visible').first()
  await search.waitFor()
  await search.fill('Times')
  await page.evaluate(() => {
    window.escapeReleases = 0
    document.addEventListener('keyup', event => {
      if (event.key === 'Escape') window.escapeReleases++
    })
  })
  const before = await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides)
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  assert.equal(await search.isVisible(), false, 'Escape closes the font dropdown while its search input is focused')
  assert.equal(await page.evaluate(() => window.escapeReleases), 0, 'The same Escape does not also reach a containing dialog')
  assert.deepEqual(await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides), before)
  await select.click()
  await search.waitFor()
  assert.equal(await search.inputValue(), '', 'Reopening resets the search')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  assert.equal(await search.isVisible(), false)
  await page.locator('body').click({ position: { x: 1, y: 1 } })
  await page.keyboard.press('Escape')
  assert.equal(await page.evaluate(() => window.escapeReleases), 1, 'Escape outside the closed dropdown remains available')
  const editor = page.locator('#editable-element-text .ProseMirror')
  const rect = await editor.boundingBox()
  await page.mouse.dblclick(rect.x + rect.width / 2, rect.y + rect.height / 2)
  await page.waitForTimeout(200)
  await editor.focus()
  await page.keyboard.press('Control+a')
  const selection = await editor.evaluate(el => ({ from: el.__pmView.state.selection.from, to: el.__pmView.state.selection.to }))
  await select.click()
  await search.waitFor()
  assert.equal(await editor.evaluate(el => el.contains(document.activeElement)), true, 'Opening the font menu preserves editing focus')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  assert.equal(await search.isVisible(), false, 'Escape closes the font menu while editing focus is retained')
  assert.deepEqual(await editor.evaluate(el => ({ from: el.__pmView.state.selection.from, to: el.__pmView.state.selection.to })), selection)
  await page.locator('[data-tooltip="More"]:visible').first().click()
  const moreMenu = page.locator('[class*="more-menu"]:visible')
  await moreMenu.waitFor()
  await page.locator('[data-tooltip="Hyperlink"]:visible').first().click()
  const linkInput = page.locator('[class*="link-popover"] input:visible')
  await linkInput.waitFor()
  await linkInput.focus()
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  assert.equal(await linkInput.isVisible(), false, 'Escape dismisses the nested link picker')
  assert.equal(await moreMenu.isVisible(), true, 'The enclosing format menu stays open')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  assert.equal(await moreMenu.isVisible(), false, 'A separate Escape dismisses the parent')
  await select.click()
  await search.waitFor()
  await page.evaluate(() => {
    const input = document.createElement('input')
    input.id = 'host-input'
    document.body.append(input)
    input.focus()
  })
  await page.keyboard.press('Escape')
  assert.equal(await search.isVisible(), true, 'Escape in an unrelated host control does not dismiss Fika menus')
  await search.focus()
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  assert.equal(await search.isVisible(), false)
  await page.evaluate(() => document.getElementById('host-input').remove())
  assert.deepEqual(errors, [])
  console.log('PASS Escape dismisses searchable dropdowns without changing the document')
} finally { await browser.close() }
