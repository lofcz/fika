import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'

const base = process.env.FIKA_TEST_URL || 'http://127.0.0.1:5178'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto(`${base}/?mode=myna&locale=en`, { waitUntil: 'networkidle' })
  const header = page.locator('[data-myna-header]')
  await header.waitFor()
  assert.equal(await page.locator('.editor-header').count(), 1)
  assert.equal(await page.locator('.layout-header').count(), 0)
  assert.equal(await header.locator('.myna-wordmark').count(), 0)
  assert.ok(!(await header.innerText()).toLowerCase().includes('myna'))
  await page.waitForFunction(() => window.__FIKA_SNAPSHOT__?.getState().snapshotLength > 0)
  assert.equal(await header.getByRole('textbox', { name: 'Design title' }).count(), 1)
  const title = header.locator('input.title-field')
  await title.click()
  await title.fill('Nordic field notes')
  await title.press('Enter')
  assert.equal(await page.evaluate(() => window.__FIKA_SLIDES__.getState().title), 'Nordic field notes')
  await title.click()
  await title.fill('Discard this')
  await title.press('Escape')
  assert.equal(await title.inputValue(), 'Nordic field notes')
  await header.getByRole('button', { name: 'File menu', exact: true }).click()
  for (const label of ['Import file', 'Export file', 'New design', 'Keyboard shortcuts', 'From beginning', 'From current slide']) {
    await page.getByText(label, { exact: true }).filter({ visible: true }).waitFor({ state: 'visible' })
  }
  await header.getByRole('button', { name: 'File menu', exact: true }).click()
  const beforeLocale = await page.evaluate(() => JSON.stringify(window.__FIKA_SLIDES__.getState().slides))
  await header.getByRole('button', { name: 'Language', exact: true }).click()
  await page.getByText('Čeština', { exact: true }).click()
  await page.waitForFunction(() => document.documentElement.lang === 'cs')
  assert.equal(await page.evaluate(() => JSON.stringify(window.__FIKA_SLIDES__.getState().slides)), beforeLocale)
  assert.equal(await title.inputValue(), 'Nordic field notes')
  await header.getByRole('button', { name: 'Jazyk', exact: true }).click()
  await page.getByText('English', { exact: true }).click()
  await page.waitForFunction(() => document.documentElement.lang === 'en')
  await page.getByRole('button', { name: /^Resize/ }).click()
  await page.getByRole('button', { name: /Story 1080/ }).click()
  await page.waitForTimeout(400)
  const original = await page.evaluate(() => JSON.stringify(window.__FIKA_SLIDES__.getState().slides))
  const snapshots = await page.evaluate(() => window.__FIKA_SNAPSHOT__.getState().snapshotLength)
  await header.getByRole('button', { name: 'File menu', exact: true }).click()
  await page.getByText('New design', { exact: true }).click()
  await page.getByRole('button', { name: /^Create new design/ }).click()
  await page.waitForFunction(() => window.__FIKA_SLIDES__.getState().slides.length === 1 && !window.__FIKA_SLIDES__.getState().slides[0].elements.length)
  assert.equal(await page.evaluate(() => window.__FIKA_SLIDES__.getState().viewportRatio), 1920 / 1080)
  await page.waitForFunction(value => window.__FIKA_SNAPSHOT__.getState().snapshotLength > value, snapshots)
  await page.evaluate(() => window.__FIKA_SNAPSHOT__.getState().unDo())
  assert.equal(await page.evaluate(() => JSON.stringify(window.__FIKA_SLIDES__.getState().slides)), original)
  await mkdir('output/myna', { recursive: true })
  await page.screenshot({ path: 'output/myna/header-wide.png' })
  await page.setViewportSize({ width: 600, height: 850 })
  const box = await header.boundingBox()
  assert.ok(box.x >= 0 && box.x + box.width <= 601)
  await page.getByRole('button', { name: 'Download', exact: true }).waitFor({ state: 'visible' })
  await page.screenshot({ path: 'output/myna/header-narrow.png' })
  await page.evaluate(() => window.__FIKA_MAIN__.getState().setReadOnly(true))
  assert.equal(await title.getAttribute('readonly'), '')
  await header.getByRole('button', { name: 'File menu', exact: true }).click()
  await page.getByText('Export file', { exact: true }).waitFor({ state: 'visible' })
  assert.equal(await page.getByText('New design', { exact: true }).count(), 0)
  assert.deepEqual(errors, [])
  console.log('Myna header: one bar, title edit/cancel, file actions, locale preservation, blank design/undo, narrow viewport, read-only export passed.')
} finally { await browser.close() }
