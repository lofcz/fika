import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
try {
 for (const mode of ['Replace', 'Replace all']) {
  const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${process.env.FIKA_TEST_URL || 'http://127.0.0.1:5173/'}?locale=en`, { waitUntil: 'domcontentloaded' })
  await page.waitForFunction(() => window.__FIKA_SNAPSHOT__?.getState().snapshotCursor >= 0)
  await page.evaluate(() => {
    const store = window.__FIKA_SLIDES__.getState()
    store.setSlides([{ id: 'literal-search', elements: [{ id: 'text', type: 'text', left: 100, top: 100, width: 700, height: 100, rotate: 0, fixedHeight: true, defaultFontName: 'Arial', defaultColor: '#000000', content: '<p style="">Price [USD]. [EUR] cost (a+b)?</p>' }] }])
    const first = window.__FIKA_SLIDES__.getState().slides[0]
    store.setSlides([first, { ...structuredClone(first), id: 'second-slide', elements: first.elements.map(el => ({ ...el, id: 'second-text' })) }])
    store.updateSlideIndex(0)
    window.__FIKA_MAIN__.getState().setSearchPanelState(true)
  })
  await page.waitForTimeout(400)
  await page.evaluate(() => window.__FIKA_SNAPSHOT__.getState().initSnapshotDatabase())
  const before = await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides)
  const input = page.getByPlaceholder('Enter text to find')
  await input.fill('Price')
  await input.press('Enter')
  await page.waitForTimeout(200)
  await page.locator('[class*="search-tabs"]').getByText('Replace', { exact: true }).click()
  await page.getByPlaceholder('Enter replacement text').fill('Cost')
  await page.getByRole('button', { name: mode, exact: true }).click()
  await page.waitForTimeout(500)
  const after = await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides)
  assert.ok(after[0].elements[0].content.includes('Cost'), 'Selected match is replaced')
  if (mode === 'Replace') assert.equal(after[1].elements[0].content, before[1].elements[0].content, 'Other matches remain unchanged')
  assert.equal(await page.evaluate(() => window.__FIKA_SNAPSHOT__.getState().snapshotCursor), 1, 'Replace creates one undo entry')
  await page.evaluate(() => document.activeElement?.blur())
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(300)
  assert.deepEqual(await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides), before, 'Undo restores the document while Find remains open')
  const count = await page.locator('[class*="search-body"] [class*="count"]').textContent()
  console.log({ count })
  assert.equal(count, '1/2', 'Undo refreshes the result count')
  const active = await page.evaluate(() => [...(CSS.highlights.get('fika-search-active') || [])].map(range => range.toString()))
  assert.deepEqual(active, ['Price'], 'Undo refreshes the highlight against the restored DOM')
  await page.evaluate(() => document.activeElement?.blur())
  await page.keyboard.press('Control+Shift+z')
  await page.waitForTimeout(300)
  assert.deepEqual(await page.evaluate(() => window.__FIKA_SLIDES__.getState().slides), after)
  assert.equal(await page.locator('[class*="search-body"] [class*="count"]').textContent(), mode === 'Replace' ? '1/1' : '0/0', 'Redo refreshes the result count, including zero matches')
  await input.fill('Unsearched phrase')
  await page.evaluate(() => document.activeElement?.blur())
  await page.keyboard.press('Control+z')
  await page.waitForTimeout(300)
  assert.equal(await page.locator('[class*="search-body"] [class*="count"]').textContent(), '0/0', 'Changing the query clears the previous search session')
  assert.deepEqual(errors, [])
  console.log('PASS Find results and highlights follow Undo and Redo', mode)
  await page.close()
 }
} finally { await browser.close() }
