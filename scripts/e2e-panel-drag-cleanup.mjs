import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${process.env.FIKA_TEST_URL || 'http://127.0.0.1:5173/'}?locale=en`, { waitUntil: 'domcontentloaded' })
  await page.waitForFunction(() => window.__FIKA_SNAPSHOT__?.getState().snapshotCursor >= 0)
  await page.keyboard.press('Control+f')
  const panel = page.locator('[class*="moveable-panel"][class*="search-panel"]')
  await panel.waitFor()
  const before = await panel.boundingBox()
  await page.mouse.move(before.x + 210, before.y + 12)
  await page.mouse.down()
  await page.mouse.move(before.x + 150, before.y + 52, { steps: 5 })
  const moved = await panel.boundingBox()
  assert.notEqual(moved.x, before.x, 'The panel is actively being dragged')
  await page.keyboard.press('Control+f')
  await panel.waitFor({ state: 'detached' })
  const handlers = await page.evaluate(() => ({ move: !!document.onmousemove, up: !!document.onmouseup }))
  console.log({ handlers })
  assert.deepEqual(handlers, { move: false, up: false }, 'Closing the panel removes drag handlers before mouse release')
  await page.mouse.up()
  await page.keyboard.press('Control+f')
  await panel.waitFor()
  const reopened = await panel.boundingBox()
  await page.mouse.move(reopened.x + 210, reopened.y + 12)
  await page.mouse.down()
  await page.mouse.move(reopened.x + 150, reopened.y + 52, { steps: 5 })
  await page.mouse.up()
  assert.notEqual((await panel.boundingBox()).x, reopened.x, 'A reopened panel still drags normally')
  assert.deepEqual(errors, [])
  console.log('PASS closing a dragged panel cleans up its handlers')
} finally { await browser.close() }
