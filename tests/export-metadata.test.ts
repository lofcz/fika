const DIGITAL_SOURCE_TYPE = 'http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia'
const METADATA: FikaExportMetadata = {
  generator: 'ScioBot',
  aiGenerated: true,
  digitalSourceType: DIGITAL_SOURCE_TYPE,
  statement: 'Generated by AI in ScioBot',
  xmpNamespace: { uri: 'https://sciobot.cz/ns/ai/1.0/', prefix: 'sciobot', properties: { aiGenerated: 'True' } },
}
const PNG_1X1 = Uint8Array.from(atob('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg=='), (c) => c.charCodeAt(0))

async function part(bytes: Uint8Array | ArrayBuffer, path: string): Promise<string> {
  const file = (await JSZip.loadAsync(bytes)).file(path)
  if (!file) throw new Error(`missing part ${path}`)
  return file.async('string')
}

async function buildDeck(configure?: (deck: pptxgen) => void): Promise<Uint8Array> {
  const deck = new pptxgen()
  deck.title = 'Houby'
  configure?.(deck)
  deck.addSlide().addText('Slide 1', { x: 1, y: 1, w: 4, h: 1 })
  return new Uint8Array(await deck.write({ outputType: 'nodebuffer' }) as Uint8Array)
}

function count(haystack: string, needle: string) {
  return haystack.split(needle).length - 1
}

async function assertPptxMetadata(bytes: Uint8Array | ArrayBuffer) {
  const app = await part(bytes, 'docProps/app.xml')
  expect(app).toContain('<Application>ScioBot</Application>')
  expect(count(app, '<Application>')).toBe(1)

  const core = await part(bytes, 'docProps/core.xml')
  expect(core).toMatch(/<cp:keywords>(?:[^<]*; )?AI-generated<\/cp:keywords>/)
  expect(core).toContain('<dc:description>Generated by AI in ScioBot</dc:description>')
  expect(core).toContain('<dc:title>Houby</dc:title>')

  const custom = await part(bytes, 'docProps/custom.xml')
  expect(custom).toContain('name="AIGenerated"><vt:bool>true</vt:bool></property>')
  expect(custom).toContain(`name="DigitalSourceType"><vt:lpwstr>${DIGITAL_SOURCE_TYPE}</vt:lpwstr></property>`)
  expect(custom).toContain('name="Generator"><vt:lpwstr>ScioBot</vt:lpwstr></property>')
  const pids = [...custom.matchAll(/pid="(\d+)"/g)].map((m) => Number(m[1]))
  expect(new Set(pids).size).toBe(pids.length)
  expect(Math.min(...pids)).toBeGreaterThanOrEqual(2)

  const rels = await part(bytes, '_rels/.rels')
  expect(count(rels, 'relationships/custom-properties')).toBe(1)
  expect(rels).toMatch(/Type="http:\/\/schemas\.openxmlformats\.org\/officeDocument\/2006\/relationships\/custom-properties" Target="docProps\/custom\.xml"/)
  const types = await part(bytes, '[Content_Types].xml')
  expect(count(types, 'PartName="/docProps/custom.xml"')).toBe(1)
  expect(types).toContain('ContentType="application/vnd.openxmlformats-officedocument.custom-properties+xml"')
}

function infoText(pdf: PDFDocument, key: string): string | undefined {
  const info = pdf.context.lookup(pdf.context.trailerInfo.Info, PDFDict)
  const value = info.get(PDFName.of(key))
  return value instanceof PDFString || value instanceof PDFHexString ? value.decodeText() : undefined
}

function xmpOf(pdf: PDFDocument): string {
  const stream = pdf.context.lookup(pdf.catalog.get(PDFName.of('Metadata')), PDFRawStream)
  expect(stream.dict.get(PDFName.of('Type'))).toBe(PDFName.of('Metadata'))
  expect(stream.dict.get(PDFName.of('Subtype'))).toBe(PDFName.of('XML'))
  return new TextDecoder().decode(stream.contents)
}

function assertPdfMetadata(pdf: PDFDocument) {
  expect(pdf.getCreator()).toBe('ScioBot')
  expect(pdf.getProducer()).toBe('ScioBot')
  expect(infoText(pdf, 'AIGenerated')).toBe('true')
  expect(infoText(pdf, 'DigitalSourceType')).toBe(DIGITAL_SOURCE_TYPE)
  expect(infoText(pdf, 'AIStatement')).toBe('Generated by AI in ScioBot')
  const xmp = xmpOf(pdf)
  expect(xmp.startsWith('<?xpacket begin="﻿" id="W5M0MpCehiHzreSzNTczkc9d"?>')).toBe(true)
  expect(xmp.endsWith('<?xpacket end="w"?>')).toBe(true)
  expect(xmp).toContain('<xmp:CreatorTool>ScioBot</xmp:CreatorTool>')
  expect(xmp).toContain('<pdf:Producer>ScioBot</pdf:Producer>')
  expect(xmp).toContain('<dc:description><rdf:Alt><rdf:li xml:lang="x-default">Generated by AI in ScioBot</rdf:li></rdf:Alt></dc:description>')
  expect(xmp).toContain(`<Iptc4xmpExt:DigitalSourceType>${DIGITAL_SOURCE_TYPE}</Iptc4xmpExt:DigitalSourceType>`)
  expect(xmp).toContain('xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/"')
  expect(xmp).toContain('xmlns:sciobot="https://sciobot.cz/ns/ai/1.0/"')
  expect(xmp).toContain('<sciobot:aiGenerated>True</sciobot:aiGenerated>')
}

describe('export metadata resolver', () => {
  it('passes the export context and normalises the result', async () => {
    const seen: unknown[] = []
    const value = await resolveExportMetadata(async (context) => { seen.push(context); return { ...METADATA, extra: 1 } as FikaExportMetadata }, { format: 'pdf', title: 'Deck' })
    expect(seen).toEqual([{ format: 'pdf', title: 'Deck' }])
    expect(value).toEqual(METADATA)
    expect(await resolveExportMetadata(() => null, { format: 'pptx', title: '' })).toBe(null)
    expect(await resolveExportMetadata(null, { format: 'pptx', title: '' })).toBe(null)
  })

  it('rejects metadata it cannot write faithfully', async () => {
    const context = { format: 'pptx' as const, title: '' }
    await expect(resolveExportMetadata(() => ({ ...METADATA, generator: ' ' }), context)).rejects.toThrow('generator')
    await expect(resolveExportMetadata(() => ({ ...METADATA, aiGenerated: 'yes' as unknown as boolean }), context)).rejects.toThrow('aiGenerated')
    await expect(resolveExportMetadata(() => ({ ...METADATA, xmpNamespace: { uri: 'x', prefix: 'rdf', properties: {} } }), context)).rejects.toThrow('prefix')
    await expect(resolveExportMetadata(() => ({ ...METADATA, xmpNamespace: { uri: 'x', prefix: 'ok', properties: { 'bad name': 'v' } } }), context)).rejects.toThrow('bad name')
    await expect(resolveExportMetadata(() => { throw new Error('entitlement lookup failed') }, context)).rejects.toThrow('entitlement lookup failed')
  })
})

describe('pptx export metadata', () => {
  it('labels a generated deck in app, core and custom properties', async () => {
    const labeled = await applyPptxExportMetadata(await buildDeck(), METADATA)
    await assertPptxMetadata(labeled)
    // Untouched core fields survive.
    expect(await part(labeled, 'docProps/core.xml')).toContain('<dcterms:created xsi:type="dcterms:W3CDTF">')
  })

  it('keeps existing keywords and descriptions and is idempotent', async () => {
    const deck = await buildDeck((d) => { d.documentProps = { keywords: 'biology, fungi', description: 'Teacher notes' } })
    expect(await part(deck, 'docProps/core.xml')).toContain('<cp:keywords>biology, fungi</cp:keywords>')
    const once = await applyPptxExportMetadata(deck, { ...METADATA, title: 'Override' })
    const twice = await applyPptxExportMetadata(once, { ...METADATA, title: 'Override' })
    const core = await part(twice, 'docProps/core.xml')
    expect(core).toContain('<cp:keywords>biology, fungi; AI-generated</cp:keywords>')
    expect(core).toContain('<dc:description>Teacher notes</dc:description>')
    expect(count(core, 'AI-generated')).toBe(1)
    expect(core).toContain('<dc:title>Override</dc:title>')
    const custom = await part(twice, 'docProps/custom.xml')
    expect(count(custom, 'name="AIGenerated"')).toBe(1)
    expect(count(custom, 'name="Generator"')).toBe(1)
    expect(count(await part(twice, '_rels/.rels'), 'custom-properties')).toBe(1)
  })

  it('updates host custom properties without dropping foreign ones', async () => {
    const zip = await JSZip.loadAsync(await buildDeck())
    zip.file('docProps/custom.xml', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n<Properties xmlns="http://schemas.openxmlformats.org/officeDocument/2006/custom-properties" xmlns:vt="http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes"><property fmtid="{D5CDD505-2E9C-101B-9397-08002B2CF9AE}" pid="7" name="Course"><vt:lpwstr>Bio 1</vt:lpwstr></property><property fmtid="{D5CDD505-2E9C-101B-9397-08002B2CF9AE}" pid="8" name="Generator"><vt:lpwstr>Other</vt:lpwstr></property></Properties>')
    const rels = await zip.file('_rels/.rels')!.async('string')
    zip.file('_rels/.rels', rels.replace('</Relationships>', '<Relationship Id="rId99" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/custom-properties" Target="docProps/custom.xml"/></Relationships>'))
    const types = await zip.file('[Content_Types].xml')!.async('string')
    zip.file('[Content_Types].xml', types.replace('</Types>', '<Override PartName="/docProps/custom.xml" ContentType="application/vnd.openxmlformats-officedocument.custom-properties+xml"/></Types>'))
    const labeled = await applyPptxExportMetadata(await zip.generateAsync({ type: 'uint8array' }), METADATA)
    await assertPptxMetadata(labeled)
    const custom = await part(labeled, 'docProps/custom.xml')
    expect(custom).toContain('pid="7" name="Course"><vt:lpwstr>Bio 1</vt:lpwstr>')
    expect(custom).not.toContain('Other')
    // Replaced properties free their pid; new ones continue after the highest kept pid.
    expect(custom).toContain('pid="8" name="AIGenerated"')
  })

  it('creates missing docProps parts with relationships and content types', async () => {
    const zip = await JSZip.loadAsync(await buildDeck())
    zip.remove('docProps/app.xml')
    zip.remove('docProps/core.xml')
    const rels = await zip.file('_rels/.rels')!.async('string')
    zip.file('_rels/.rels', rels.replace(/<Relationship [^>]*(?:core-properties|extended-properties)"[^>]*\/>/g, ''))
    const types = await zip.file('[Content_Types].xml')!.async('string')
    zip.file('[Content_Types].xml', types.replace(/<Override PartName="\/docProps\/[^"]+"[^>]*\/>/g, ''))
    const labeled = await applyPptxExportMetadata(await zip.generateAsync({ type: 'uint8array' }), { ...METADATA, title: 'Houby' })
    await assertPptxMetadata(labeled)
    const nextRels = await part(labeled, '_rels/.rels')
    expect(nextRels).toContain('relationships/metadata/core-properties" Target="docProps/core.xml"')
    expect(nextRels).toContain('relationships/extended-properties" Target="docProps/app.xml"')
    const ids = [...nextRels.matchAll(/Id="([^"]+)"/g)].map((m) => m[1])
    expect(new Set(ids).size).toBe(ids.length)
    const nextTypes = await part(labeled, '[Content_Types].xml')
    expect(nextTypes).toContain('<Override PartName="/docProps/core.xml" ContentType="application/vnd.openxmlformats-package.core-properties+xml"/>')
    expect(nextTypes).toContain('<Override PartName="/docProps/app.xml" ContentType="application/vnd.openxmlformats-officedocument.extended-properties+xml"/>')
  })

  it('escapes host strings', async () => {
    const labeled = await applyPptxExportMetadata(await buildDeck(), { ...METADATA, generator: 'A&B <Bot>', statement: 'Made by "A&B"' })
    expect(await part(labeled, 'docProps/app.xml')).toContain('<Application>A&amp;B &lt;Bot&gt;</Application>')
    expect(await part(labeled, 'docProps/core.xml')).toContain('<dc:description>Made by &quot;A&amp;B&quot;</dc:description>')
  })
})

describe('pdf export metadata', () => {
  it('writes Info keys and an XMP packet that survive a save/load round trip', async () => {
    const pdf = await PDFDocument.create()
    pdf.setTitle('Houby')
    pdf.addPage([720, 405])
    applyPdfExportMetadata(pdf, METADATA, { title: 'Houby' })
    const loaded = await PDFDocument.load(await pdf.save(), { updateMetadata: false })
    assertPdfMetadata(loaded)
    expect(loaded.getTitle()).toBe('Houby')
    expect(xmpOf(loaded)).toContain('<dc:title><rdf:Alt><rdf:li xml:lang="x-default">Houby</rdf:li></rdf:Alt></dc:title>')
  })

  it('omits optional fields and encodes non-ASCII text', async () => {
    const pdf = await PDFDocument.create()
    pdf.addPage()
    applyPdfExportMetadata(pdf, { generator: 'Žluťoučký', aiGenerated: false, digitalSourceType: DIGITAL_SOURCE_TYPE })
    const loaded = await PDFDocument.load(await pdf.save(), { updateMetadata: false })
    expect(loaded.getCreator()).toBe('Žluťoučký')
    expect(infoText(loaded, 'AIGenerated')).toBe('false')
    expect(infoText(loaded, 'AIStatement')).toBe(undefined)
    const xmp = xmpOf(loaded)
    expect(xmp).toContain('<xmp:CreatorTool>Žluťoučký</xmp:CreatorTool>')
    expect(xmp).not.toContain('dc:description')
    expect(xmp).not.toContain('sciobot')
  })
})

/**
 * Drives the real export worker module (the code path behind both the export
 * dialog and `exportPresentationPptx` / `exportPresentationPdf`) with a small
 * recorded deck.
 */
describe('export worker writes metadata', () => {
  const replies = new Map<number, { value?: unknown; error?: string }>()
  let onmessage: (event: { data: unknown }) => Promise<void>
  let nextId = 0
  const request = async <T>(task: string, data: unknown): Promise<T> => {
    const id = ++nextId
    await onmessage({ data: { id, task, data } })
    const reply = replies.get(id)!
    if (reply.error) throw new Error(reply.error)
    return reply.value as T
  }

  beforeAll(async () => {
    const scope = globalThis as unknown as { onmessage?: unknown; postMessage?: unknown }
    const previous = { onmessage: scope.onmessage, postMessage: scope.postMessage }
    scope.postMessage = (message: { id: number; value?: unknown; error?: string }) => { replies.set(message.id, message) }
    await import('../src/workers/export.worker')
    onmessage = scope.onmessage as typeof onmessage
    scope.onmessage = previous.onmessage
    // The module captured `scope` itself; keep postMessage pointing at the collector.
  })

  it('labels a regenerated PPTX deck', async () => {
    const { pptx, commands } = recordPptxExport()
    pptx.title = 'Houby'
    pptx.author = 'Fika'
    pptx.addSlide().addText('Houby jsou plodnice hub', { x: 1, y: 1, w: 6, h: 1 })
    pptx.addSlide().addText('Druhý slajd', { x: 1, y: 1, w: 6, h: 1 })
    const bytes = await request<ArrayBuffer>('pptx', { commands, stamp: null, metadata: METADATA })
    await assertPptxMetadata(bytes)
    expect(await part(bytes, 'ppt/slides/slide1.xml')).toContain('Houby jsou plodnice hub')
  })

  it('labels a retained source package without a watermark', async () => {
    const bytes = await request<ArrayBuffer>('stamp', { bytes: await buildDeck(), watermark: null, images: null, metadata: METADATA })
    await assertPptxMetadata(bytes)
  })

  it('leaves the default PPTX metadata alone without a resolver result', async () => {
    const { pptx, commands } = recordPptxExport()
    pptx.addSlide()
    const bytes = await request<ArrayBuffer>('pptx', { commands, stamp: null, metadata: null })
    expect(await part(bytes, 'docProps/app.xml')).toContain('<Application>Microsoft Office PowerPoint</Application>')
    expect((await JSZip.loadAsync(bytes)).file('docProps/custom.xml')).toBe(null)
  })

  it('labels a PDF deck', async () => {
    await request('pdf-start', { title: 'Houby', watermark: null, light: null, dark: null, metadata: METADATA })
    for (let i = 0; i < 2; i++) await request('pdf-page', { bytes: PNG_1X1.slice().buffer, format: 'image/png', width: 720, height: 405, dark: false })
    const pdf = await PDFDocument.load(await request<ArrayBuffer>('pdf-save', null), { updateMetadata: false })
    expect(pdf.getPageCount()).toBe(2)
    expect(pdf.getTitle()).toBe('Houby')
    assertPdfMetadata(pdf)
    expect(pdf.catalog.get(PDFName.of('Pages'))).toBeTruthy()
    expect(pdf.catalog.lookup(PDFName.of('Pages'), PDFDict).lookup(PDFName.of('Kids'), PDFArray).size()).toBe(2)
  })

  it('keeps Fika as the PDF creator without a resolver result', async () => {
    await request('pdf-start', { title: 'Houby', watermark: null, light: null, dark: null, metadata: null })
    await request('pdf-page', { bytes: PNG_1X1.slice().buffer, format: 'image/png', width: 720, height: 405, dark: false })
    const pdf = await PDFDocument.load(await request<ArrayBuffer>('pdf-save', null), { updateMetadata: false })
    expect(pdf.getCreator()).toBe('Fika')
    expect(pdf.catalog.get(PDFName.of('Metadata'))).toBe(undefined)
  })
})
