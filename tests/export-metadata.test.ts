import JSZip from 'jszip'
import pptxgen from 'pptxgenjs-plus'
import { PDFArray, PDFDict, PDFDocument, PDFHexString, PDFName, PDFRawStream, PDFString } from 'pdf-lib'
import { resolveExportMetadata, type FikaExportMetadata } from '../src/configs/exportMetadata'
import { applyPptxExportMetadata } from '../src/utils/pptxExportMetadata'
import { applyPdfExportMetadata } from '../src/utils/pdfExportMetadata'
